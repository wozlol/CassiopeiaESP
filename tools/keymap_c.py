#!/usr/bin/env python3
# Usage: keymap_c.py   Writes components/a11_keys/include/a11_keymap.h from keymap/a11_keymap.json.
import json, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
d = json.load(open(os.path.join(root, 'keymap', 'a11_keymap.json')))
CUSTOM = {'on': 0x100, 'off': 0x101, 'backlight': 0x102}
SHOW = {'-': 'Minus', '=': 'Equals', '[': 'LeftBracket', ']': 'RightBracket', '\\': 'Backslash', ';': 'Semicolon',
        "'": 'Apostrophe', '`': 'Grave', ',': 'Comma', '.': 'Period', '/': 'Slash'}
rows = []
for k in d['keys']:
    a, b = sorted(k['pairs'][0])
    code = k['hid'] if k['hid'] is not None else CUSTOM[k['name']]
    rows.append((a, b, code, SHOW.get(k['name'], k['name'])))
rows.sort(key=lambda r: r[2])
out = ['// Generated by tools/keymap_c.py from keymap/a11_keymap.json. Do not edit.',
       '// Pads are nRF pad numbers, code is a USB HID Keyboard/Keypad usage (page 0x07) or a custom code from 0x100.',
       '#pragma once', '#include <stdint.h>', '',
       '#define A11_KEY_ON 0x100', '#define A11_KEY_OFF 0x101', '#define A11_KEY_BACKLIGHT 0x102', '',
       'typedef struct { uint8_t pad_a, pad_b; uint16_t code; const char *name; } a11_keydef_t;', '',
       'static const a11_keydef_t A11_KEYMAP[] = {']
for a, b, code, name in rows:
    out.append('    {%d, %d, 0x%03X, "%s"},' % (a, b, code, name))
out += ['};', '#define A11_KEY_COUNT %d' % len(rows), '']
open(os.path.join(root, 'components', 'a11_keys', 'include', 'a11_keymap.h'), 'w').write('\n'.join(out))
print('wrote %d keys' % len(rows))
