#!/usr/bin/env python3
# Usage: kbsleep_sets.py   Splits the keyboard pads into two groups so that every key joins one pad of each group, then writes nrf/kbscan/wake_sets.h.
# While the nRF sleeps it drives group A low and senses group B, so a press of any key wakes it with no polling and no current draw.
import json, os, sys, collections
here = os.path.dirname(os.path.abspath(__file__))
km = json.load(open(os.path.join(here, '..', 'keymap', 'a11_keymap.json')))
adj = collections.defaultdict(set)
for k in km['keys']:
    for a, b in k['pairs']:
        adj[a].add(b); adj[b].add(a)
col = {}
for s in sorted(adj):
    if s in col: continue
    col[s] = 0; st = [s]
    while st:
        u = st.pop()
        for v in adj[u]:
            if v not in col: col[v] = 1 - col[u]; st.append(v)
            elif col[v] == col[u]: sys.exit('Keyboard graph is not two sided, pads %d and %d clash. Wake on any key needs another scheme.' % (u, v))
A = sum(1 << p for p in col if col[p] == 0)
B = sum(1 << p for p in col if col[p] == 1)
out = os.path.join(here, '..', 'nrf', 'kbscan', 'wake_sets.h')
open(out, 'w').write('// Generated by tools/kbsleep_sets.py from keymap/a11_keymap.json, do not edit.\n#define WAKE_DRIVE_MASK 0x%08XUL\n#define WAKE_SENSE_MASK 0x%08XUL\n' % (A, B))
print('A (driven low) %s\nB (sensed) %s\nwrote %s' % (sorted(p for p in col if col[p] == 0), sorted(p for p in col if col[p] == 1), out))
