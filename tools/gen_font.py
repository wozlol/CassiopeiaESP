#!/usr/bin/env python3
# Usage: gen_font.py <terminus-font-4.49.1 directory>
# Writes components/a11_font/a11_font_data.c from the Terminus BDF files, plain 1 bit per pixel tables, no compression.
# Terminus Font is under the SIL Open Font License 1.1, see components/a11_font/OFL.TXT.
import os, sys, re
src = sys.argv[1]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'components', 'a11_font')
SIZES = [(6, 12, 12), (8, 16, 16), (10, 18, 18), (12, 24, 24), (14, 28, 28), (16, 32, 32)]

def parse(path, cw, ch):
    lines = open(path, encoding='latin-1').read().split('\n')
    ascent = None
    glyphs = {}
    i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith('FONT_ASCENT'):
            ascent = int(l.split()[1])
        if l.startswith('STARTCHAR'):
            enc = bbx = None
            i += 1
            while not lines[i].startswith('BITMAP'):
                if lines[i].startswith('ENCODING'): enc = int(lines[i].split()[1])
                if lines[i].startswith('BBX'): bbx = [int(x) for x in lines[i].split()[1:]]
                i += 1
            w, h, xo, yo = bbx
            rows = []
            i += 1
            while not lines[i].startswith('ENDCHAR'):
                rows.append(lines[i])
                i += 1
            if enc is not None and 0 <= enc <= 0xFFFF:
                cell = [[0] * cw for _ in range(ch)]
                top = ascent - (yo + h)
                for r, hexrow in enumerate(rows):
                    nbits = len(hexrow) * 4
                    v = int(hexrow, 16)
                    for b in range(w):
                        if (v >> (nbits - 1 - b)) & 1:
                            x, y = xo + b, top + r
                            if 0 <= x < cw and 0 <= y < ch:
                                cell[y][x] = 1
                glyphs[enc] = cell
        i += 1
    return glyphs

out = ['// Generated by tools/gen_font.py from Terminus Font 4.49.1 (SIL OFL 1.1). Do not edit.',
       '#include "sdkconfig.h"', '#include "a11_font.h"', '']
tables = []
for (cw, ch, n) in SIZES:
    for style in ('n', 'b'):
        path = os.path.join(src, 'ter-u%d%s.bdf' % (n, style))
        g = parse(path, cw, ch)
        cps = sorted(g)
        rb = 1 if cw <= 8 else 2
        name = 'f%dx%d%s' % (cw, ch, style)
        big = (cw, ch) not in ((6, 12), (8, 16))
        if big: out.append('#if !defined(CONFIG_A11_FONT_SMALL_ONLY)')
        out.append('static const uint16_t %s_cps[] = {%s};' % (name, ','.join('0x%X' % c for c in cps)))
        data = []
        for c in cps:
            for row in g[c]:
                v = 0
                for x in range(cw): v = (v << 1) | row[x]
                v <<= (8 * rb - cw)
                data += [(v >> (8 * (rb - 1 - k))) & 0xFF for k in range(rb)]
        out.append('static const uint8_t %s_bits[] = {%s};' % (name, ','.join(str(b) for b in data)))
        if big: out.append('#endif')
        tables.append((name, cw, ch, rb, len(cps), style, big))
        print(name, len(cps), 'glyphs', len(data), 'bytes')
out.append('const a11_font_t A11_FONTS[] = {')
for name, cw, ch, rb, n, style, big in tables:
    if big: out.append('#if !defined(CONFIG_A11_FONT_SMALL_ONLY)')
    out.append('    {%d, %d, %d, %d, %d, %s_cps, %s_bits},' % (cw, ch, rb, 1 if style == 'b' else 0, n, name, name))
    if big: out.append('#endif')
out.append('};')
out.append('const int A11_FONT_COUNT = sizeof A11_FONTS / sizeof A11_FONTS[0];')
open(os.path.join(root, 'a11_font_data.c'), 'w').write('\n'.join(out) + '\n')
