# Usage: bin2h.py <in.bin> <out.h> <flash address>
import sys
data = open(sys.argv[1], 'rb').read()
while len(data) % 4:
    data += b'\xff'
addr = int(sys.argv[3], 0)
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/bin2h.py, do not edit.\n#pragma once\n#include <stdint.h>\n')
    f.write('#define NRF_IMAGE_ADDR 0x%08XUL\n#define NRF_IMAGE_LEN %dUL\n' % (addr, len(data)))
    f.write('static const uint8_t NRF_IMAGE[] = {\n')
    for i in range(0, len(data), 16):
        f.write('  ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
